def _summary_text(summary) -> str:
    if is_dataclass(summary):
        return repr(asdict(summary))
    if isinstance(summary, Mapping):
        return repr(dict(summary))
    return repr(vars(summary) if hasattr(summary, "__dict__") else summary)


def _summary_indicates_problem(summary) -> bool:
    for name in ("is_valid", "valid", "ok", "passed", "shape_matches"):
        if hasattr(summary, name) and getattr(summary, name) is False:
            return True
        if isinstance(summary, Mapping) and summary.get(name) is False:
            return True

    for name in (
        "errors",
        "failures",
        "issues",
        "missing_columns",
        "extra_columns",
        "missing_metrics",
        "extra_steps",
        "unexpected_steps",
        "parameter_mismatches",
        "unexpected_parameter_conditions",
    ):
        try:
            value = _field(summary, name)
        except AssertionError:
            continue
        if value:
            return True

    return False


