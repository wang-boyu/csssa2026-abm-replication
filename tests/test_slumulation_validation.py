    def test_smoke_output_helper_uses_runner_and_writer_injection_boundaries(
        self,
    ) -> None:
        api = _validation_api()
        runner_module = importlib.import_module("slumulation.runner")
        calls: list[tuple[str, object]] = []
        sentinel_rows = (
            _row_for_step(0),
            _row_for_step(1),
        )

        def run_rows_stub(*args, **kwargs):
            calls.append(("run", kwargs))
            self.assertIn("seed", kwargs)
            return sentinel_rows

        def write_rows_stub(path, rows):
            materialized_rows = tuple(rows)
            calls.append(("write", (Path(path), materialized_rows)))
            self.assertEqual(materialized_rows, sentinel_rows)

        with tempfile.TemporaryDirectory() as directory:
            output_path = Path(directory) / "mesa-smoke.csv"
            with ExitStack() as stack:
                stack.enter_context(
                    mock.patch.object(
                        runner_module,
                        "run_behavior_space_rows",
                        side_effect=run_rows_stub,
                    )
                )
                stack.enter_context(
                    mock.patch.object(
                        runner_module,
                        "write_behavior_space_rows",
                        side_effect=write_rows_stub,
                    )
                )
                if hasattr(api.module, "run_behavior_space_rows"):
                    stack.enter_context(
                        mock.patch.object(
                            api.module,
                            "run_behavior_space_rows",
                            side_effect=run_rows_stub,
                        )
                    )
                if hasattr(api.module, "write_behavior_space_rows"):
                    stack.enter_context(
                        mock.patch.object(
                            api.module,
                            "write_behavior_space_rows",
                            side_effect=write_rows_stub,
                        )
                    )

                _call_with_supported_keywords(
                    api.write_mesa_smoke_output,
                    output_path=output_path,
                    path=output_path,
                    csv_path=output_path,
                    experiment_name="Typical Run",
                    experiment_names=("Typical Run",),
                    selected_experiment_names=("Typical Run",),
                    repetitions=1,
                    repetition_count=1,
                    base_seed=api.DEFAULT_MESA_BASE_SEED,
                    run_rows_fn=run_rows_stub,
                    run_behavior_space_rows_fn=run_rows_stub,
                    row_runner=run_rows_stub,
                    write_rows_fn=write_rows_stub,
                    write_behavior_space_rows_fn=write_rows_stub,
                    writer=write_rows_stub,
                )

        self.assertEqual([call[0] for call in calls], ["run", "write"])

