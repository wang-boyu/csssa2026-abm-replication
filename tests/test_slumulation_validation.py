def _call_with_supported_keywords(function, *args, **kwargs):
    signature = inspect.signature(function)
    parameters = signature.parameters
    accepts_kwargs = any(
        parameter.kind == inspect.Parameter.VAR_KEYWORD
        for parameter in parameters.values()
    )
    supported_kwargs = (
        kwargs
        if accepts_kwargs
        else {name: value for name, value in kwargs.items() if name in parameters}
    )
    return function(*args, **supported_kwargs)


def _call_loader(function, path: Path):
    signature = inspect.signature(function)
    if len(signature.parameters) == 0:
        raise AssertionError(f"{function.__name__} must accept a CSV path.")

    first_parameter = next(iter(signature.parameters))
    path_kwargs = {
        "path": path,
        "csv_path": path,
        "file_path": path,
        "table_path": path,
    }
    if first_parameter in path_kwargs:
        return _call_with_supported_keywords(function, **path_kwargs)

    return function(path)


